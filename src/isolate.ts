import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import type {
  IsolationPlan,
  TargetUnit,
  WorktreeIsolationAllocation,
} from './types.js';

function slugify(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function planWorktreeIsolation(
  units: TargetUnit[],
  basePort = 3100,
): IsolationPlan {
  const worktrees = units
    .filter(
      (u) =>
        u.kind === 'worktree' &&
        typeof u.worktreePath === 'string' &&
        u.worktreePath.trim().length > 0,
    )
    .sort((a, b) => a.id.localeCompare(b.id));

  const allocations: WorktreeIsolationAllocation[] = worktrees.map(
    (wt, index) => {
      const assignedPort = basePort + index * 10;
      const assignedVitePort = basePort + 2000 + index * 10;
      const wtPath = wt.worktreePath!;
      const repoDir = path.basename(path.resolve(wtPath));
      const repoDirSlug = slugify(repoDir) || 'repo';
      const unitSlug = slugify(wt.id.replace(/^wt:/, '')) || `wt${index}`;
      const composeProjectName = `${repoDirSlug}-${unitSlug}`
        .replace(/--+/g, '-')
        .replace(/^-|-$/g, '');
      const envFilePath = path.join(wtPath, '.env.worktree.local');
      const envFileContent = [
        '# Generated by crossfire isolate',
        `PORT=${assignedPort}`,
        `APP_PORT=${assignedPort}`,
        `VITE_PORT=${assignedVitePort}`,
        `COMPOSE_PROJECT_NAME=${composeProjectName}`,
        '',
      ].join('\n');

      return {
        unitId: wt.id,
        worktreePath: wtPath,
        assignedPort,
        assignedVitePort,
        composeProjectName,
        envFilePath,
        envFileContent,
      };
    },
  );

  return {
    basePort,
    allocations,
    writtenFiles: [],
  };
}

export async function applyWorktreeIsolation(
  plan: IsolationPlan,
  write: boolean,
): Promise<IsolationPlan> {
  if (!write) {
    return {
      ...plan,
      writtenFiles: [],
    };
  }

  const writtenFiles: string[] = [];
  for (const alloc of plan.allocations) {
    await fs.writeFile(alloc.envFilePath, alloc.envFileContent, 'utf-8');
    writtenFiles.push(alloc.envFilePath);
  }

  return {
    ...plan,
    writtenFiles,
  };
}
